/**
 * Reads the shading ramps out of the theme in globals.css and writes them as a GIMP palette
 * (.gpl), which Aseprite opens directly. The CSS stays the single source of truth.
 */
import { RAMP_NAMES, RAMP_STEPS, type RampName, hexToRgb } from '../src/lib/palette';

export type Ramps = Record<RampName, string[]>;

export function parseRamps(css: string): Ramps {
  const out = {} as Ramps;
  for (const name of RAMP_NAMES) {
    out[name] = Array.from({ length: RAMP_STEPS }, (_, i) => {
      const match = css.match(new RegExp(`--color-${name}-${i}:\\s*(#[0-9a-fA-F]{6})\\s*;`));
      if (!match) throw new Error(`globals.css is missing --color-${name}-${i}`);
      return match[1]!.toLowerCase();
    });
  }
  return out;
}

export function toGpl(ramps: Ramps): string {
  const rows = RAMP_NAMES.flatMap((name) =>
    ramps[name].map((hex, i) => {
      const [r, g, b] = hexToRgb(hex);
      return `${String(r).padStart(3)} ${String(g).padStart(3)} ${String(b).padStart(3)}\t${name}-${i}`;
    }),
  );
  return [
    'GIMP Palette',
    'Name: My Three Body CV',
    `Columns: ${RAMP_STEPS}`,
    '# Generated by `pnpm palette` from src/app/globals.css. Do not edit by hand.',
    ...rows,
    '',
  ].join('\n');
}
