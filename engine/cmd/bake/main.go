// Command bake renders the black hole sprite sheet at build time. It writes
// raster/blackhole_gen.go (palette indices the engine blits) and a PNG preview in
// ../public/sprites/blackhole-16.png with colours read from src/app/globals.css.
// Run from engine/: go run ./cmd/bake
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"image"
	"image/png"
	"log"
	"os"

	"github.com/SkyeWalker360/my-three-body-cv/engine/internal/csspal"
	"github.com/SkyeWalker360/my-three-body-cv/engine/raster"
)

const (
	genPath = "raster/blackhole_gen.go"
	pngPath = "../public/sprites/blackhole-16.png"
	cssPath = "../src/app/globals.css"
)

func main() {
	n := raster.BlackHoleW * raster.BlackHoleH
	sheet := make([]uint8, n*raster.BlackHoleFrames)
	for k := 0; k < raster.BlackHoleFrames; k++ {
		raster.BakeBlackHole(sheet[k*n:(k+1)*n], k)
	}
	writeGo(sheet)
	writePNG(sheet)
}

func writeGo(sheet []uint8) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/bake; DO NOT EDIT.\n\npackage raster\n\n")
	fmt.Fprintf(&b, "var blackHoleSheet = [%d]uint8{", len(sheet))
	for i, v := range sheet {
		if i%32 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%d,", v)
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(genPath, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s", genPath)
}

func writePNG(sheet []uint8) {
	pal, err := csspal.Load(cssPath)
	if err != nil {
		log.Fatal(err)
	}
	w, h := raster.BlackHoleW, raster.BlackHoleH
	img := image.NewRGBA(image.Rect(0, 0, w*raster.BlackHoleFrames, h))
	for k := 0; k < raster.BlackHoleFrames; k++ {
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				if c := sheet[k*w*h+y*w+x]; c != raster.Transparent {
					img.Set(k*w+x, y, pal[c])
				}
			}
		}
	}
	f, err := os.Create(pngPath)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	if err := png.Encode(f, img); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s", pngPath)
}
